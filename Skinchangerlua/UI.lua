                })
            Tween:Play()

            task.delay(0.13, function()
                if not Open then
                    Root.Visible = false
                end
            end)
        end
    end

    -- header drag
    local DragArea = Create("TextButton", {
        BackgroundTransparency = 1,
        BorderSizePixel = 0,
        Size = UDim2.new(1, 0, 0, 44),
        Text = "",
        AutoButtonColor = false,
        ZIndex = 40,
        Parent = Header,
    })

    DragArea.InputBegan:Connect(function(Input)
        if
            Input.UserInputType == Enum.UserInputType.MouseButton1
            or Input.UserInputType == Enum.UserInputType.Touch
        then
            Dragging = true
            DragStart = Input.Position
            DragOrigin = Root.Position
        end
    end)

    Connections[#Connections + 1] = UserInputService.InputChanged:Connect(function(Input)
        if not Dragging then
            return
        end

        if
            Input.UserInputType == Enum.UserInputType.MouseMovement
            or Input.UserInputType == Enum.UserInputType.Touch
        then
            local Delta = Input.Position - DragStart

            Root.Position = UDim2.new(0.5, DragOrigin.X.Offset + Delta.X, 0.5, DragOrigin.Y.Offset + Delta.Y)

            Clamp()
        end
    end)

    Connections[#Connections + 1] = UserInputService.InputEnded:Connect(function(Input)
        if
            Input.UserInputType == Enum.UserInputType.MouseButton1
            or Input.UserInputType == Enum.UserInputType.Touch
        then
            Dragging = false
        end
    end)

    Connections[#Connections + 1] = UserInputService.InputBegan:Connect(function(Input)
        if Input.KeyCode == Enum.KeyCode.RightControl then
            SetOpen(not Open)
        end
    end)

    -- keep the window inside the viewport when the camera changes size
    local CameraConnection = nil

    local function BindCamera()
        local Camera = workspace.CurrentCamera

        if CameraConnection then
            CameraConnection:Disconnect()
            CameraConnection = nil
        end

        if Camera then
            CameraConnection = Camera:GetPropertyChangedSignal("ViewportSize"):Connect(UpdateScale)
        end

        UpdateScale()
    end

    Connections[#Connections + 1] = workspace:GetPropertyChangedSignal("CurrentCamera"):Connect(BindCamera)
    BindCamera()

    SelectTab(1)

    local Window = {
        Gui = Gui,
        Root = Root,
        Screen = Screen,
        Tabs = Tabs,
        Pages = Pages,
        Cards = Cards,
        CardsByName = CardsByName,
        SelectTab = SelectTab,
        SelectCard = SelectCard,
        SetOpen = SetOpen,
        UpdateScale = UpdateScale,
    }

    function Window.Destroy()
        for _, Connection in ipairs(Connections) do
            pcall(function()
                Connection:Disconnect()
            end)
        end

        if CameraConnection then
            pcall(function()
                CameraConnection:Disconnect()
            end)
        end

        if Gui then
            Gui:Destroy()
        end
    end

    if Cards[1] then
        SelectCard(Cards[1])
    end

    return Window
end


local function Create(ClassName, Properties)
    local Object = Instance.new(ClassName)
    local Parent = nil

    if Properties then
        Parent = Properties.Parent

        for Key, Value in pairs(Properties) do
            if Key ~= "Parent" then
                Object[Key] = Value
            end
        end
    end

    if Parent then
        Object.Parent = Parent
    end

    return Object
end

local function Corner(Object, Radius)
    local CornerObject = Instance.new("UICorner")
    CornerObject.CornerRadius = UDim.new(0, Radius or 2)
    CornerObject.Parent = Object
    return CornerObject
end

local function Stroke(Object, Color, Thickness)
    local StrokeObject = Instance.new("UIStroke")
    StrokeObject.Color = Color
    StrokeObject.Thickness = Thickness or 1
    StrokeObject.ApplyStrokeMode = Enum.ApplyStrokeMode.Border
    StrokeObject.Parent = Object
    return StrokeObject
end

local function Text(Properties)
    local Label = Instance.new("TextLabel")
    Label.BackgroundTransparency = 1
    Label.BorderSizePixel = 0
    Label.TextColor3 = Theme.Text
    Label.TextSize = 12
    Label.TextXAlignment = Enum.TextXAlignment.Left
    Label.TextYAlignment = Enum.TextYAlignment.Center
    Label.TextWrapped = false
    Label.RichText = false

    if CustomFont then
        local Applied = pcall(function()
            Label.FontFace = CustomFont
        end)

        if not Applied then
            Label.Font = Enum.Font.Code
        end
    else
        Label.Font = Enum.Font.Code
    end

    local Parent = nil

    if Properties then
        Parent = Properties.Parent

        for Key, Value in pairs(Properties) do
            if Key ~= "Parent" then
                Label[Key] = Value
            end
        end
    end

    if Parent then
        Label.Parent = Parent
    end

    return Label
end

-- A surface with the two-stage border used across the whole interface:
-- a one pixel outer frame (#121213 / #161616) and a one pixel inner stroke.
local function Surface(Parent, Position, Size, Fill, StrokeColor, FarColor, Radius)
    local Outer = Create("Frame", {
        BackgroundColor3 = FarColor,
        BorderSizePixel = 0,
        Position = Position,
        Size = Size,
    })

    local Inner = Create("Frame", {
        BackgroundColor3 = Fill,
        BorderSizePixel = 0,
        Position = UDim2.fromOffset(1, 1),
        Size = UDim2.new(1, -2, 1, -2),
    })

    Corner(Outer, Radius)
    Corner(Inner, Radius)

    local InnerStroke = Stroke(Inner, StrokeColor, 1)

    Inner.Parent = Outer
    Outer.Parent = Parent

    return Outer, Inner, InnerStroke
end


local function Base64Decode(Input)
    local Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local Lookup = {}

    for Index = 1, #Alphabet do
        Lookup[string.sub(Alphabet, Index, Index)] = Index - 1
    end

    local Output = {}
    local Buffer = 0
    local Bits = 0

    for Index = 1, #Input do
        local Character = string.sub(Input, Index, Index)

        if Character == "=" then
            break
        end

        local Value = Lookup[Character]

        if Value then
            Buffer = Buffer * 64 + Value
            Bits = Bits + 6

            if Bits >= 8 then
                Bits = Bits - 8

                local Divisor = 2 ^ Bits
                local Byte = math.floor(Buffer / Divisor)

                Output[#Output + 1] = string.char(Byte % 256)
                Buffer = Buffer % Divisor
            end
        end
    end

    return table.concat(Output)
end

local function LoadCustomFont()
    if type(writefile) ~= "function" or type(getcustomasset) ~= "function" then
        return nil
    end

    local Success, Result = pcall(function()
        local Folder = "UnableSkins"

        pcall(function()
            if type(isfolder) == "function" and type(makefolder) == "function" and not isfolder(Folder) then
                makefolder(Folder)
            end
        end)

        local Data = Base64Decode(FONT_B64)
        local Path = Folder .. "/ProggyClean.ttf"
        local Wrote = pcall(writefile, Path, Data)

        if not Wrote then
            Path = "ProggyClean.ttf"
            Wrote = pcall(writefile, Path, Data)
        end

        if not Wrote then
            return nil
        end

        local Asset = getcustomasset(Path)

        if type(Asset) ~= "string" or Asset == "" then
            return nil
        end

        return Font.new(Asset)
    end)

    if Success and typeof(Result) == "Font" then
        return Result
    end

    return nil
end

